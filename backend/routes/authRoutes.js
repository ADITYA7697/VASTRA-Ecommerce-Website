const r = require("express").Router();
const c = require("../controllers/authController");
const { protect } = require("../middleware/auth");
const wrap = require("../utils/asyncHandler");
r.post("/register", wrap(c.register));
r.post("/signup", wrap(c.register));
r.post("/login", wrap(c.login));
r.post("/login-phone", wrap(c.loginPhone));
const identity = require("../controllers/identityController");
r.post("/google", wrap(identity.googleLogin));
r.post("/phone/send-otp", wrap(identity.sendPhoneOtp));
r.post("/phone/verify-otp", wrap(identity.verifyPhoneOtp));
r.post("/phone/link/send-otp", protect, wrap(identity.sendLinkOtp));
r.post("/phone/link/verify-otp", protect, wrap(identity.verifyLinkOtp));
r.post("/logout", wrap(c.logout));
r.post("/logout-all", protect, wrap(c.logoutAll));
r.post("/forgot-password", wrap(c.forgotPassword));
r.post("/reset-password", wrap(c.resetPassword));
r.get("/me", protect, wrap(c.me));
r.get("/admin/users", protect, require("../middleware/auth").adminOnly, wrap(c.adminUsers));
r.get("/profile", protect, wrap(c.me));
r.put("/profile", protect, wrap(c.updateProfile));
r.post("/wishlist/:productId", protect, wrap(c.toggleWishlist));
module.exports = r;
